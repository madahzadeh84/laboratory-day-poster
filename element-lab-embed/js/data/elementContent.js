export function getElementHistory(element, yearDiscovered) {
  if (yearDiscovered === "Ancient") {
    return `${element.name} از دوران باستان برای انسان شناخته‌شده بوده است.`;
  }
  if (yearDiscovered) {
    const localizedYear = String(yearDiscovered).replace(/\d/g, (digit) => "۰۱۲۳۴۵۶۷۸۹"[digit]);
    return `سال کشف ${element.name} در داده‌های علمی ${localizedYear} میلادی ثبت شده است.`;
  }
  return `برای ${element.name} سال کشف قطعی در داده‌های مرجع ثبت نشده است.`;
}

